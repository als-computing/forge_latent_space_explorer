function compress(bytes: number[], target: number): number[] {
  const length = bytes.length
  if (target >= length) return bytes
  const segSize = length / target
  const segments = new Array<number>(target).fill(0)
  for (let i = 0; i < length; i++) {
    const seg = Math.min(Math.floor(i / segSize), target - 1)
    segments[seg] ^= bytes[i]
  }
  return segments
}

export async function deriveProjectName(uris: string[]): Promise<string> {
  const concatenated = uris.join('')
  const encoded = new TextEncoder().encode(concatenated)
  const hashBuffer = await crypto.subtle.digest('SHA-256', encoded)
  const bytes = Array.from(new Uint8Array(hashBuffer))
  const compressed = compress(bytes, 4)
  return compressed.map(b => WORDLIST[b]).join('-')
}
